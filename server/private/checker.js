async function runPendingAction(){
  if(!pendingAction)return;
  const {type,id,value}=pendingAction;
  const errEl=document.getElementById('pendingError');
  try{
    let res;
    if(type==='role'){
      res=await apiFetch('/api/admin/users/'+id+'/role',{method:'PATCH',body:JSON.stringify({role:value})});
    } else if(type==='active'){
      res=await apiFetch('/api/admin/users/'+id+'/active',{method:'PATCH',body:JSON.stringify({active:value})});
    } else if(type==='delete'){
      res=await apiFetch('/api/admin/users/'+id,{method:'DELETE'});
    }
    if(res&&!res.ok){
      const data=await res.json().catch(()=>({}));
      const msg=data.error==='cannot delete your own account'?'Нельзя удалить собственную учётную запись':(data.error||'Не удалось выполнить действие');
      if(errEl){errEl.textContent=msg;errEl.style.display='block';}
      return;
    }
  }catch(e){
    if(errEl){errEl.textContent='Ошибка сети';errEl.style.display='block';}
    return;
  }
  closeModal();
  renderAdminPanel();
}

