// Сворачивает карточки результатов в компактный вид: шапка (иконка+
// заголовок) и всё до тегов включительно остаются видны всегда, а списки/
// таблицы/примечания после тегов (обычно самая объёмная часть) прячутся за
// клик по шапке. По одному коду часто находится 7-10 карточек сразу — до
// этого все они разворачивались полностью, и результат приходилось долго
// листать. Работает поверх уже готовой разметки карточек (без переделки
// каждого из ~25 шаблонов карточек в render()) — просто переносит все
// элементы после последнего из {.rh,.tags} внутрь схлопываемой обёртки.
function compactifyCards(container){
  resCards(container).forEach(card=>{
    if(card.classList.contains('collapsible'))return;
    const anchor=card.querySelector(':scope > .tags')||card.querySelector(':scope > .rh');
    if(!anchor)return;
    const rest=[];
    let sib=anchor.nextElementSibling;
    while(sib){const next=sib.nextElementSibling;rest.push(sib);sib=next;}
    if(!rest.length)return;
    // Карточки-списки для выбора кода (строка кликабельна -> goToCode) не
    // сворачиваем — это не «детали», а сам результат, который должен быть
    // виден сразу (иначе пришлось бы сначала кликать «раскрыть», чтобы
    // просто увидеть список кандидатов для перехода).
    if(rest.some(el=>el.querySelector('[onclick^="goToCode"]')))return;
    const more=document.createElement('div');
    more.className='card-more';
    rest.forEach(el=>more.appendChild(el));
    card.appendChild(more);
    card.classList.add('collapsible');
    const rh=card.querySelector(':scope > .rh');
    if(rh){
      const chev=document.createElement('span');
      chev.className='card-chevron';
      chev.textContent='▾';
      rh.appendChild(chev);
      rh.addEventListener('click',()=>card.classList.toggle('open'));
    }
  });
  if(container.id==='result'){
    const btn=document.getElementById('expandAllBtn');
    const hasCollapsible=!!container.querySelector('.card.collapsible');
    btn.style.display=hasCollapsible?'':'none';
    btn.textContent='▾ Развернуть все карточки';
    btn.dataset.state='closed';
  }
}
