// Пункт 9 таблицы 1 приложения № 2 — особый режим для лица государства Союза,
// временно проживавшего за границей не менее 12 месяцев. Его беспошлинная норма
// (5 000 € и никакого весового предела) задана не приложением № 1, а пунктом 4
// приложения № 3; ставка на превышение — пунктом 9 таблицы 1.
// Формулировка ставки в акте: «30 процентов от стоимости, но не менее 4 евро за
// 1 кг веса в части превышения стоимостной нормы 5 000 евро в эквиваленте».
// В отличие от пунктов 1-4 той же таблицы, слов «в части превышения стоимостной
// нормы» после «от стоимости» здесь нет — процент считается от всей стоимости, а
// не от превышения. Это единственное место расчёта, где формулировка акта
// допускает прочтение, и карточка приводит её дословно, чтобы читатель проверил.
// Режим действует только для багажа: и пункт 4 приложения № 3, и пункт 9
// таблицы 1 говорят о сопровождаемом и (или) несопровождаемом багаже.
const PERSONAL_RESIDENT={eur:5000, pct:30, eurKg:4, channels:['air','land'],
  wording:'30 процентов от стоимости, но не менее 4 евро за 1 кг веса в части превышения стоимостной нормы 5 000 евро в эквиваленте'};

function personalResidentDuty(valueEur,kg){
  if(valueEur<=PERSONAL_RESIDENT.eur)return {eur:0,within:true,
    note:'стоимость не превышает 5 000 € — освобождение по п.4 приложения № 3, вес значения не имеет'};
  const byV=valueEur*PERSONAL_RESIDENT.pct/100, byW=kg*PERSONAL_RESIDENT.eurKg;
  return {eur:Math.max(byV,byW),byV:byV,byW:byW,within:false,
    note:'max(30% от всей стоимости '+valueEur.toFixed(2)+' € = '+byV.toFixed(2)+' €; 4 € × '+kg.toFixed(3)+' кг = '+byW.toFixed(2)+' €)'};
}

// Сбор за таможенные операции. Для товаров электронной торговли, приобретённых
// одним физическим лицом для личного пользования, п.38² Инструкции к ПКМ КР № 79
// даёт фиксированные 6 сомов за 1 кг брутто; в остальных случаях применяется
// п.38 (0,4% с вилкой 5-2500 расчётных показателей). При устном декларировании
// сбор не уплачивается вовсе — п.7 ч.3 ст.41 Закона КР № 52.
function personalFee(ecom,kg,valueSom){
  if(ecom)return {sum:6*kg,note:'6 сомов за 1 кг брутто (п.38² Инструкции к ПКМ КР № 79)'};
  return {sum:customsFeeGoods(valueSom),note:'0,4% от стоимости, вилка 500–250 000 сом (п.38 той же Инструкции)'};
}

