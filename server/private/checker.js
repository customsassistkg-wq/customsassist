// Прибавляет n месяцев к календарной дате "YYYY-MM-DD" (или к сегодняшней
// дате зрителя, если value пуст), не трогая часовые пояса вообще: работает
// только с числами год/месяц/день, а Date.UTC()+setUTCMonth() используется
// исключительно как календарный калькулятор, а не как реальный момент
// времени. Раньше здесь был new Date(value+'T00:00:00') — это парсится как
// ПОЛНОЧЬ ПО МЕСТНОМУ ВРЕМЕНИ браузера, и при повторном нажатии «+1 месяц»
// от уже выставленной даты в часовом поясе восточнее UTC (Бишкек, UTC+6)
// .toISOString() после такого прыжка туда-обратно через локальное время
// иногда «съедал» день.
function addMonthsToDateStr(value,n){
  let y,m,d;
  if(value){
    [y,m,d]=value.split('-').map(Number);
  } else {
    const now=new Date();
    y=now.getFullYear();m=now.getMonth()+1;d=now.getDate();
  }
  const dt=new Date(Date.UTC(y,m-1,d));
  dt.setUTCMonth(dt.getUTCMonth()+n);
  return dt.toISOString().slice(0,10);
}

function fmtDate(iso){
  if(!iso)return '';
  const d=new Date(iso);
  return String(d.getDate()).padStart(2,'0')+'.'+String(d.getMonth()+1).padStart(2,'0')+'.'+d.getFullYear();
}

// last_login_at/last_seen_at — реальные моменты времени (не календарные
// даты вроде подписки), поэтому в отличие от fmtCalDate тут корректно
// показывать их в местном времени зрителя через локальные getX(), без
// UTC-трюка, который применяется только к «оплачено до».
function fmtDateTime(iso){
  if(!iso)return '';
  const d=new Date(iso);
  return String(d.getDate()).padStart(2,'0')+'.'+String(d.getMonth()+1).padStart(2,'0')+'.'+d.getFullYear()
    +' '+String(d.getHours()).padStart(2,'0')+':'+String(d.getMinutes()).padStart(2,'0');
}

// Срок подписки сервер хранит как «конец календарного дня по UTC»
// (input[type=date] "2026-09-30" → "2026-09-30T23:59:59.999Z"), именно
// чтобы включить весь выбранный день целиком. Если форматировать это через
// fmtDate() (локальные компоненты даты браузера), в любом часовом поясе
// восточнее UTC (в т.ч. Бишкек, UTC+6) 23:59:59.999Z уже перевалило за
// полночь по местному времени — дата в карточке сдвигалась на день вперёд
// относительно того, что реально ввёл администратор. Календарные даты вида
// «оплачено до» нужно читать в той же системе отсчёта (UTC), в которой их
// закодировали, а не в локальном поясе зрителя.
function fmtCalDate(iso){
  if(!iso)return '';
  const d=new Date(iso);
  return String(d.getUTCDate()).padStart(2,'0')+'.'+String(d.getUTCMonth()+1).padStart(2,'0')+'.'+d.getUTCFullYear();
}

