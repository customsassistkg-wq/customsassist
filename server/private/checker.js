// Экспорт таблицы пользователей в CSV с BOM и разделителем ";" — именно
// точка с запятой, а не запятая: Excel в русской локали трактует запятую
// как десятичный разделитель и без BOM показывает кириллицу битой.
function exportAdminUsersCSV(){
  const header=['Email','Роль','Статус','Онлайн','Подписка','Дата регистрации','Последний вход'];
  const lines=[header.join(';')];
  for(const u of adminUsers){
    const role=u.role==='admin'?'Админ':'Пользователь';
    const status=u.active?'Активен':'Отключён';
    const online=u.online?'Онлайн':'Оффлайн';
    let sub;
    if(u.role==='admin')sub='—';
    else if(!u.subscription_expires_at)sub='Без ограничения';
    else sub=(new Date(u.subscription_expires_at)<new Date()?'Истекла ':'До ')+fmtCalDate(u.subscription_expires_at);
    const reg=u.created_at?fmtDate(u.created_at):'';
    const lastLogin=u.last_login_at?fmtDateTime(u.last_login_at):'';
    lines.push([u.email,role,status,online,sub,reg,lastLogin].map(v=>'"'+String(v).replace(/"/g,'""')+'"').join(';'));
  }
  const blob=new Blob(['﻿'+lines.join('\r\n')],{type:'text/csv;charset=utf-8;'});
  const url=URL.createObjectURL(blob);
  const a=document.createElement('a');
  a.href=url;
  a.download='users_'+new Date().toISOString().slice(0,10)+'.csv';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

