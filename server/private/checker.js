function parseRateInfo(raw){
  if(raw===null||raw===undefined||raw===''){return {type:'unknown'};}
  if(typeof raw==='number'){return {type:'simple',pct:raw};}
  const s=String(raw).trim();
  let m=s.match(/^(\d+(?:[.,]\d+)?)\s*\(\d+[^)]?\)$/);
  if(m)return {type:'simple',pct:parseFloat(m[1].replace(',','.'))};
  // Легковые автомобили: «15, либо 12,5, но не менее X евро за 1 см³ объема
  // двигателя, в зависимости от того, какая из исчисленных сумм таможенной
  // пошлины ниже» — это не выбор декларанта, а потолок 15% и пол
  // max(12,5%; специфическая часть): пошлина = min(15%, max(12,5%, X €/см³)).
  m=s.match(/^(\d+(?:[.,]\d+)?)\s*,?\s*либо\s*(\d+(?:[.,]\d+)?)\s*,?\s*но не менее\s*(\d+(?:[.,]\d+)?)\s*евро\s*за\s*(.+?)\s*,\s*в зависимости от того,\s*какая из исчисленных сумм таможенной пошлины ниже\.?$/i);
  if(m)return {type:'minof',pct:parseFloat(m[1].replace(',','.')),pct2:parseFloat(m[2].replace(',','.')),eur:parseFloat(m[3].replace(',','.')),unit:m[4].trim()};
  if(/либо/i.test(s))return {type:'complex',raw:s};
  m=s.match(/^(\d+(?:[.,]\d+)?)\s*плюс\s*(\d+(?:[.,]\d+)?)\s*евро\s*за\s*(.+)$/i);
  if(m)return {type:'plus',pct:parseFloat(m[1].replace(',','.')),eur:parseFloat(m[2].replace(',','.')),unit:m[3].trim()};
  m=s.match(/^(\d+(?:[.,]\d+)?)\s*,?\s*но не менее\s*(\d+(?:[.,]\d+)?)\s*евро\s*за\s*(.+)$/i);
  if(m)return {type:'max',pct:parseFloat(m[1].replace(',','.')),eur:parseFloat(m[2].replace(',','.')),unit:m[3].trim()};
  m=s.match(/^(\d+(?:[.,]\d+)?)\s*евро\s*за\s*(.+)$/i);
  if(m)return {type:'specific',eur:parseFloat(m[1].replace(',','.')),unit:m[2].trim()};
  m=s.match(/^(\d+(?:[.,]\d+)?)\s*доллар\S*\s*США\s*за\s*(.+)$/i);
  if(m)return {type:'usd',usd:parseFloat(m[1].replace(',','.')),unit:m[2].trim()};
  return {type:'complex',raw:s};
}

// Единые ставки таможенных пошлин, налогов на легковые автомобили, ввозимые
// физическим лицом для личного пользования — таблица 2, пункт 3 приложения № 2
// к Решению Совета ЕЭК от 20.12.2017 № 107 (в ред. решений Совета ЕЭК № 91 от
// 01.11.2018, № 35 от 17.03.2022, № 59 от 15.04.2022, № 123 от 19.08.2022,
// № 151 от 23.09.2022, № 30 от 30.03.2023, № 94 от 27.09.2023, № 87 от 18.10.2024).
// Сверено 09.09.2026 по публикации ЕЭК, см. SOURCE_AUDIT.avto. Решение Совета
// ЕЭК № 35 от 24.02.2026 правит приложение № 3 (распоряжение электромобилями),
// ставок не касается.
//
// Это ЕДИНАЯ ставка: по пункту 3 статьи 266 ТК ЕАЭС она заменяет собой и пошлину,
// и налоги, поэтому НДС сверх неё не начисляется — начисляется только
// национальный сбор за таможенные операции.
//
// Электромобили подсубпозиции 8703 80 000, квадроциклы, снегоходы и мотоциклы
// идут не по единой ставке, а совокупным таможенным платежом (пункты 1 и 4 той
// же таблицы), поэтому здесь их нет и льготный режим для них не предлагается.
//
// Не более 3 лет: [верхняя граница стоимости в евро, % от стоимости, минимум €/см³].
const CAR_RATE_NEW=[[8500,54,2.5],[16700,48,3.5],[42300,48,5.5],[84500,48,7.5],[169000,48,15],[null,48,20]];
// Более 3, но не более 5 лет: [верхняя граница рабочего объёма, см³; ставка €/см³].
const CAR_RATE_3_5=[[1000,1.5],[1500,1.7],[1800,2.5],[2300,2.7],[3000,3],[null,3.6]];
// Более 5 лет.
const CAR_RATE_OVER5=[[1000,3],[1500,3.2],[1800,3.5],[2300,4.8],[3000,5],[null,5.7]];
const CAR_AGE_BANDS=[['new','не более 3 лет с момента выпуска'],['y3_5','более 3, но не более 5 лет'],['over5','более 5 лет']];
function carAgeBandLabel(band){const b=CAR_AGE_BANDS.find(x=>x[0]===band);return b?b[1]:''}
function carAgeBandForYear(year){
  if(!year)return null;
  const age=new Date().getFullYear()-year;
  return age<=3?'new':(age<=5?'y3_5':'over5');
}

// Размер единой ставки в евро плюс пояснение, как он получен.
// Для автомобилей не старше 3 лет ставка — процент от стоимости, но не менее
// фиксированной суммы за см³, поэтому нужна и стоимость в евро, и объём.
function personalCarDuty(band,volume,valueEur){
  if(band==='new'){
    for(const [cap,pct,minRate] of CAR_RATE_NEW){
      if(cap===null||valueEur<=cap){
        const byPct=valueEur*pct/100, byVol=minRate*volume;
        const use=Math.max(byPct,byVol);
        return {eur:use,
          note:'единая ставка '+pct+'% от стоимости = '+byPct.toFixed(2)+' € и минимум '+minRate+' €/см³ × '+volume+' см³ = '+byVol.toFixed(2)+' € — применяется '+(byVol>byPct?'минимум':'процент от стоимости')};
      }
    }
  }
  const table=band==='y3_5'?CAR_RATE_3_5:CAR_RATE_OVER5;
  for(const [cap,rate] of table){
    if(cap===null||volume<=cap){
      return {eur:rate*volume,note:'единая ставка '+rate+' €/см³ × '+volume+' см³ ('+carAgeBandLabel(band)+')'};
    }
  }
  return {eur:0,note:''};
}


// Таможенный сбор за таможенные операции, связанные с выпуском товаров — Закон КР №52 от 24.04.2019
// (ст.41, ст.44 ч.3) + ставки в Инструкции к Пост. КМ КР №79 от 13.02.2020 (в ред. Пост. №444 от 29.06.2026):
// обычные товары — 0,4% от таможенной стоимости, не менее 5 РП и не более 2500 РП (п.38 Инструкции);
// автотранспорт физлиц для личного пользования — фиксированно 22 РП (п.38³). 1 РП = 100 сом
// (Пост. ЖК КР №1115-III от 15.06.2006, не менялось). Это отдельный от пошлины/НДС платёж; не путать со
// сбором за таможенное сопровождение (ст.42 Закона — узкий, за км, актуален только для транзита/конвоя).
const RP_SOM=100;
const CUSTOMS_FEE_CAR_PERSONAL=22*RP_SOM;
function customsFeeGoods(customsValueSom){
  return Math.min(Math.max(customsValueSom*0.004, 5*RP_SOM), 2500*RP_SOM);
}

