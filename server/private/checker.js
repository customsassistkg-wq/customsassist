function prefNormC(s){return (s||'').toLowerCase().replace(/ё/g,'е').replace(/[^a-zа-я0-9]/g,'')}
// Слово-в-начале плюс вхождение для запросов от пяти знаков: «мали» не должно
// находить Малави, а «котдивуар» и «тиморлесте» — должны, хотя официальное
// название начинается со слова «Республика».
function prefCountryHit(name,q){
  const full=prefNormC(name);
  if(!full||!q)return false;
  if(name.split(/[\s\-–—]+/).some(w=>prefNormC(w).startsWith(q)))return true;
  return q.length>=5&&full.indexOf(q)>=0;
}
function findPrefByCountry(query){
  const q=prefNormC(query);
  if(q.length<3||/^\d+$/.test(q))return[];
  const alias=PREF_C_ALIAS[q];
  const out=new Map();
  const add=(name,kind)=>{
    if(!out.has(name))out.set(name,{name:name,dev:false,ldc:false,fta:null});
    const rec=out.get(name);
    if(kind==='dev')rec.dev=true; else if(kind==='ldc')rec.ldc=true; else rec.fta=kind;
  };
  for(const c of PREF_DEV_C)if(c===alias||prefCountryHit(c,q))add(c,'dev');
  for(const c of PREF_LDC_C)if(c===alias||prefCountryHit(c,q))add(c,'ldc');
  for(const f of PREF_FTA){
    if(f.n===alias||prefCountryHit(f.n,q)){
      // Иран и Монголия входят и в перечень развивающихся стран: соглашение
      // не отменяет ЕСТП, поэтому оба режима показываются в одной карточке.
      let key=null;
      for(const k of out.keys())if(prefCountryHit(k,prefNormC(f.n)))key=k;
      if(key)out.get(key).fta=f; else add(f.n,f);
    }
  }
  return Array.from(out.values());
}

