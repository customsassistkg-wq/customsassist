// ПАКЕТНАЯ ЗАГРУЗКА СПЕЦИФИКАЦИИ (Excel/CSV)
// ═══════════════════════════════════════════
// .xlsx — это zip с XML внутри, а распаковывать zip браузер умеет сам
// (DecompressionStream('deflate-raw')), поэтому SheetJS и подобные библиотеки
// не нужны: тащить в самодостаточный однофайловый HTML ещё мегабайт кода ради
// одной кнопки было бы дороже, чем разобрать формат руками. Если браузер
// старый и DecompressionStream в нём нет, честно просим сохранить файл как CSV.

function zipEntries(buf){
  const dv=new DataView(buf), u8=new Uint8Array(buf);
  // Центральный каталог ищем с конца: EOCD стоит в самом хвосте файла и может
  // иметь комментарий после себя, поэтому идём назад до сигнатуры.
  let eocd=-1;
  for(let i=u8.length-22;i>=0&&i>u8.length-70000;i--){
    if(dv.getUint32(i,true)===0x06054b50){eocd=i;break}
  }
  if(eocd<0)throw new Error('это не zip/xlsx-файл');
  let n=dv.getUint16(eocd+10,true), off=dv.getUint32(eocd+16,true);
  const out={};
  for(let k=0;k<n;k++){
    if(dv.getUint32(off,true)!==0x02014b50)break;
    const method=dv.getUint16(off+10,true);
    const csize=dv.getUint32(off+20,true);
    const fnLen=dv.getUint16(off+28,true), exLen=dv.getUint16(off+30,true), cmLen=dv.getUint16(off+32,true);
    const lho=dv.getUint32(off+42,true);
    const name=new TextDecoder('utf-8').decode(u8.subarray(off+46,off+46+fnLen));
    // Длины полей в локальном заголовке своих собственных — брать их из
    // центрального каталога нельзя, extra-поле там обычно другое.
    const lfnLen=dv.getUint16(lho+26,true), lexLen=dv.getUint16(lho+28,true);
    const start=lho+30+lfnLen+lexLen;
    out[name]={method:method,data:u8.subarray(start,start+csize)};
    off+=46+fnLen+exLen+cmLen;
  }
  return out;
}

async function zipRead(entries,name){
  const e=entries[name];
  if(!e)return null;
  if(e.method===0)return new TextDecoder('utf-8').decode(e.data);
  if(typeof DecompressionStream==='undefined')throw new Error('браузер не умеет распаковывать xlsx — сохраните файл в CSV');
  const ds=new DecompressionStream('deflate-raw');
  const blob=new Blob([e.data]);
  const stream=blob.stream().pipeThrough(ds);
  return await new Response(stream).text();
}

function colIndex(ref){
  const m=/^([A-Z]+)/.exec(ref||'');
  if(!m)return 0;
  let n=0;
  for(const ch of m[1])n=n*26+(ch.charCodeAt(0)-64);
  return n-1;
}

// Все листы книги по порядку — массивами массивов строк. Порядок и файлы листов — из workbook.xml и его
// связей, а не по именам: порядок файлов в архиве не обязан совпадать с порядком листов, а файл листа может
// называться как угодно. Калькулятор берёт первый лист (readXlsx), чат помощника — все: инвойс и упаковочный
// лист часто лежат в одной книге на разных листах.
async function readXlsxSheets(buf){
  const entries=zipEntries(buf),xmlDom=s=>new DOMParser().parseFromString(s,'application/xml');
  const shared=[];
  const ssXml=await zipRead(entries,'xl/sharedStrings.xml');
  if(ssXml){
    for(const si of xmlDom(ssXml).getElementsByTagName('si')){
      let s='';
      for(const t of si.getElementsByTagName('t'))s+=t.textContent;
      shared.push(s);
    }
  }
  const sheets=[];
  try{
    const wb=await zipRead(entries,'xl/workbook.xml'),rels=await zipRead(entries,'xl/_rels/workbook.xml.rels');
    if(wb&&rels){
      const target={};
      for(const r of xmlDom(rels).getElementsByTagName('Relationship'))target[r.getAttribute('Id')]='xl/'+(r.getAttribute('Target')||'').replace(/^\/?xl\//,'').replace(/^\.\//,'');
      for(const sh of xmlDom(wb).getElementsByTagName('sheet')){
        const p=target[sh.getAttribute('r:id')||sh.getAttribute('id')];
        const xml=p&&await zipRead(entries,p);
        if(xml)sheets.push({name:sh.getAttribute('name')||'',rows:xlsxRows(xmlDom(xml),shared)});
      }
    }
  }catch(e){}
  if(!sheets.length){
    const any=Object.keys(entries).filter(k=>/^xl\/worksheets\/.*\.xml$/.test(k)).sort()[0];
    if(!any)throw new Error('в файле нет листов');
    sheets.push({name:'',rows:xlsxRows(xmlDom(await zipRead(entries,any)),shared)});
  }
  return sheets;
}
function xlsxRows(dom,shared){
  const rows=[];
  for(const row of dom.getElementsByTagName('row')){
    const cells=[];
    for(const c of row.getElementsByTagName('c')){
      const idx=colIndex(c.getAttribute('r'));
      const type=c.getAttribute('t');
      let val='';
      if(type==='s'){
        const v=c.getElementsByTagName('v')[0];
        val=v?(shared[parseInt(v.textContent,10)]||''):'';
      } else if(type==='inlineStr'){
        for(const t of c.getElementsByTagName('t'))val+=t.textContent;
      } else {
        const v=c.getElementsByTagName('v')[0];
        val=v?v.textContent:'';
      }
      while(cells.length<idx)cells.push('');
      cells[idx]=val;
    }
    rows.push(cells);
  }
  return rows;
}
// Возвращает первый лист книги как массив массивов строк.
async function readXlsx(buf){
  return (await readXlsxSheets(buf))[0].rows;
}
// Текстовый файл — в UTF-8, а если так не читается, в windows-1251: CSV из Excel в русской локали
// сохраняется именно в ней, и file.text() превращал кириллицу в знаки замены.
async function fileText(file){
  const buf=await file.arrayBuffer(),t=new TextDecoder('utf-8').decode(buf);
  return t.indexOf(String.fromCharCode(0xfffd))>=0?new TextDecoder('windows-1251').decode(buf):t;
}

function readCsv(text){
  const first=(text.split(/\r?\n/)[0]||'');
  // Разделитель определяем по первой строке: Excel в русской локали сохраняет
  // CSV с точкой с запятой, и запятая внутри такой строки — это дробная часть.
  const counts=[[';',(first.match(/;/g)||[]).length],['\t',(first.match(/\t/g)||[]).length],[',',(first.match(/,/g)||[]).length]];
  counts.sort((a,b)=>b[1]-a[1]);
  const d=counts[0][1]>0?counts[0][0]:';';
  return text.split(/\r?\n/).filter(l=>l.trim()!=='').map(line=>{
    const out=[];let cur='',q=false;
    for(let i=0;i<line.length;i++){
      const ch=line[i];
      if(q){
        if(ch==='"'&&line[i+1]==='"'){cur+='"';i++}
        else if(ch==='"')q=false;
        else cur+=ch;
      } else if(ch==='"')q=true;
      else if(ch===d){out.push(cur);cur=''}
      else cur+=ch;
    }
    out.push(cur);
    return out;
  });
}

// Заголовки ищем по смыслу, а не по позиции: у брокеров спецификации приходят
// с разными подписями колонок, а порядок столбцов у каждого свой.
const SPEC_COLS=[
  ['code',/(тн\s*вэд|тнвэд|^код|hs\s*code|hscode)/i],
  ['value',/(стоим|сумма|цена|invoice|amount|value|price)/i],
  ['cur',/(валют|curr)/i],
  ['qty',/(кол-?во|количест|qty|quantity|мест)/i],
  ['weight',/(вес|масс|weight|нетто)/i],
  ['name',/(наимен|товар|описан|descr|name)/i]
];

function specMapHeader(row){
  const map={};
  let hits=0;
  row.forEach((cell,i)=>{
    const s=String(cell||'').trim();
    if(!s)return;
    for(const [key,re] of SPEC_COLS){
      if(map[key]===undefined&&re.test(s)){map[key]=i;hits++;break}
    }
  });
  return hits>=2?map:null;
}

function specNum(v){
  if(v===null||v===undefined)return 0;
  const s=String(v).replace(/\s|\u00a0/g,'').replace(',','.').replace(/[^0-9.\-]/g,'');
  const n=parseFloat(s);
  return isFinite(n)?n:0;
}

// Разбирает строки таблицы в позиции партии, объясняя по каждой строке, что с
// ней не так: молча выбросить строку спецификации нельзя — брокер должен
// видеть, что именно не попало в расчёт.
async function specRowsToItems(rows){
  let map=null,start=0;
  for(let i=0;i<Math.min(rows.length,10);i++){
    const m=specMapHeader(rows[i]);
    if(m&&m.code!==undefined){map=m;start=i+1;break}
  }
  // Без строки заголовка считаем, что колонки идут в самом очевидном порядке:
  // код, наименование, стоимость.
  if(!map){map={code:0,name:1,value:2,cur:3,qty:4,weight:5};start=0}
  const eurRate=nbkrRateFor('EUR')||0, usdRate=nbkrRateFor('USD')||0;
  const lines=[];
  for(let i=start;i<rows.length;i++){
    const rawCode=String(rows[i][map.code]!==undefined?rows[i][map.code]:'').trim();
    const codeDigits=rawCode.replace(/\D/g,'');
    if(codeDigits)lines.push({i:i,rawCode:rawCode,codeDigits:codeDigits});
  }
  // Строки сверх предела в предпросмотр не попадают, поэтому и на сервер не отправляются.
  const cut=Math.max(0,lines.length-SPEC_MAX_ROWS);
  lines.length=Math.min(lines.length,SPEC_MAX_ROWS);
  // Строка ЕТТ по коду и подсказка для кода, которого в ЕТТ нет, — с сервера (specLookup в private/base.js).
  const look=lines.length?await engine('specLookup',[...new Set(lines.map(l=>l.codeDigits))]):{};
  const out=[];
  for(const {i,rawCode,codeDigits} of lines){
    const r=rows[i];
    const rec={line:i+1,raw:rawCode,problems:[],warns:[],item:null};
    const lk=look[codeDigits]||{n:0,hint:'код не найден в ЕТТ'};
    const ett=lk.ett;
    if(!ett){
      rec.problems.push(lk.n
        ?('код неоднозначен — в ЕТТ '+lk.n+' подходящих подсубпозиций, укажите полный 10-значный код')
        :lk.hint);
      out.push(rec);continue;
    }
    const cur=(String(map.cur!==undefined?(r[map.cur]||''):'').trim().toUpperCase()||'СОМ');
    const curNorm=CALC_CURRENCIES.indexOf(cur)>=0?cur:(cur==='KGS'||cur==='СОМ'||cur===''?'СОМ':null);
    if(!curNorm){rec.problems.push('неизвестная валюта «'+cur+'»');out.push(rec);continue}
    const curRate=curNorm==='СОМ'?1:(nbkrRateFor(curNorm)||0);
    if(!curRate){rec.problems.push('нет курса '+curNorm+' — курсы НБКР не загружены');out.push(rec);continue}
    const valueCur=specNum(map.value!==undefined?r[map.value]:0);
    if(!valueCur)rec.warns.push('стоимость не распознана — позиция уйдёт в партию с нулём');
    const parsed=parseRateInfo(ett[3]);
    const qty=specNum(map.qty!==undefined?r[map.qty]:0);
    const weight=specNum(map.weight!==undefined?r[map.weight]:0);
    if((parsed.type==='specific'||parsed.type==='plus'||parsed.type==='max'||parsed.type==='usd'||parsed.type==='minof')&&!qty){
      rec.warns.push('ставка считается от количества ('+(parsed.unit||'')+'), а колонка количества пуста — специфическая часть пошлины будет нулевой');
    }
    if(parsed.type==='complex')rec.warns.push('ставка сложная («'+trunc(String(ett[3]),40)+'») — пошлину по этой позиции нужно задать вручную');
    if(parsed.type==='unknown')rec.warns.push('ставка в базе не указана — пошлина будет нулевой');
    rec.item={code:ett[0],name:ett[1],unit:ett[2],rate:ett[3],cur:curNorm,curRate:curRate,
      valueCur:valueCur,valueSom:valueCur*curRate,weight:weight,qty:qty,eurRate:eurRate,usdRate:usdRate,
      manualDuty:0,auto:null};
    out.push(rec);
  }
  return {recs:out,cut:cut};
}

