const engineCache=new Map();
async function engine(fn,...args){
  if(typeof ENGINE_API!=='undefined')return ENGINE_API[fn](...args);
  const key=fn+'|'+JSON.stringify(args);
  if(engineCache.has(key))return engineCache.get(key);
  const p=(async()=>{
    const res=await apiFetch('/api/engine',{method:'POST',body:JSON.stringify({fn:fn,args:args})});
    const data=await res.json().catch(()=>({}));
    if(!res.ok){const e=new Error(data.error||('HTTP '+res.status));e.status=res.status;e.code=data.error;throw e}
    return data.result;
  })();
  // До выкладки новой базы ответ на тот же запрос не меняется — повтор берётся из памяти
  // страницы; ошибка не запоминается, старые записи вытесняются.
  engineCache.set(key,p);
  p.catch(()=>engineCache.delete(key));
  if(engineCache.size>400)engineCache.delete(engineCache.keys().next().value);
  return p;
}
