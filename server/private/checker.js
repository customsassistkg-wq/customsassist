function lkSameRate(a,b){return String(a).replace(/\./g,',')===String(b).replace(/\./g,',')}
function lkBest(opts){return opts.map(o=>o.rate).sort((a,b)=>lkRateKey(a)-lkRateKey(b))[0]}

