-- Страницы документов в журнале AI-помощника.
--
-- С 17.09.2026 браузер присылает страницы сканов и фото, приложенных к чату, по одной сразу при
-- прикреплении (POST /api/assistant/read), и модель читает каждую отдельным вызовом. Это расход, который
-- должен попасть в счёт, но не вопрос: лимит вопросов по тарифу считает только kind = 'question', лимит
-- страниц — kind = 'read'. Прежние записи — вопросы (значение по умолчанию).
--
-- Выкладывать до перезапуска API: маршрут пишет и читает эту колонку в каждом запросе.

alter table assistant_log add column if not exists kind text not null default 'question'
  check (kind in ('question', 'read'));
