-- Принятие правил использования (пользовательского соглашения).
--
-- Статья 114 Цифрового кодекса КР от 31.07.2025 № 178 не допускает пользования
-- сервисом без пользовательского соглашения и обязывает хранить запись,
-- подтверждающую его условия и факт заключения, весь срок соглашения и три
-- года после. Здесь — действующая редакция, которую принял пользователь, и
-- дата: по ней страница решает, показывать ли окно «Принимаю». Сама запись для
-- трёх лет пишется ещё и в admin_audit_log (action = 'terms_accepted'): строка
-- users удаляется вместе с аккаунтом, а журнал переживает удаление (0003).
-- ponytail: записи журнала старше трёх лет после удаления аккаунта не чистятся —
-- добавить чистку, когда первым из них будет три года (не раньше 2029 года).
--
-- Выкладывать до перезапуска API: middleware/auth.js читает terms_version.

alter table users add column if not exists terms_version text;
alter table users add column if not exists terms_accepted_at timestamptz;
