-- Подтверждение почты становится обязательным для входа.
--
-- До этой миграции действовала «мягкая» политика: учётная запись создавалась,
-- сразу логинилась и работала, а в шапке висела полоса «подтвердите адрес».
-- Владелец решил закрыть доступ без подтверждения — иначе регистрация на
-- выдуманный адрес даёт полноценный доступ (так в базе и появился
-- esenbek@exampl.com с опечаткой в домене, которому ничего не дойдёт).
--
-- Существующие учётные записи помечаются подтверждёнными намеренно, по
-- прямому решению владельца. Из пятнадцати десять не подтверждены, и восемь из
-- них заведены 03.09.2026 — до того, как подтверждение вообще появилось. Им
-- никогда не приходило письма, и отрезать их задним числом за невыполнение
-- требования, которого не существовало, было бы несправедливо и вылилось бы в
-- поток обращений. Требование действует для всех, кто регистрируется после
-- этой миграции.
--
-- Отметка ставится текущим временем, а не датой создания: это дата решения о
-- признании, а не дата подтверждения, которого не было. Врать в данных о том,
-- что человек что-то подтверждал, нельзя.
update users
   set email_verified_at = now()
 where email_verified_at is null;
