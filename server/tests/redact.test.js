// node server/tests/redact.test.js
// Персональные данные не уходят в модель (services/assistant.js, redactPersonal):
// вычищается то, что помечено или однозначно по форме; остаётся всё, без чего ответ
// и расчёт развалятся — код ТН ВЭД, суммы, вес, валюта, страна, номер и дата документа.
// Без сети: чистая функция и один проход ask() с подменённым fetch, чтобы убедиться,
// что до запроса к модели доходит уже очищенный текст.
const assert = require('node:assert/strict');
process.env.AI_API_KEY = 'test';
const nbkr = require('../src/services/nbkrRates');
nbkr.getRates = async () => ({ date: '16.09.2026', usd: 87.45, eur: 100.9086, rates: { USD: 87.45, EUR: 100.9086 } });
const { ask, redactPersonal } = require('../src/services/assistant');

(async () => {
  // ── что вырезается ──
  const gone = [
    ['Почта продавца: ivanov.petr@example.kg, ответьте', /example\.kg|ivanov/i, '[почта]'],
    ['Контакт +996 555 123 456 по грузу', /\+996|555 123/, '[телефон]'],
    ['Тел.: 0700123456', /0700123456/, '[телефон]'],
    ['Оплата картой 4276 3800 1234 5678', /4276|5678/, '[карта]'],
    ['ИНН 12345678901234, плательщик', /12345678901234/, '[идентификатор]'],
    ['IBAN: KG820012345678901234', /KG8200|12345678901234/, '[счёт]'],
    ['Паспорт AN2345678 выдан', /AN2345678/, '[документ]'],
    ['Адрес: г. Бишкек, ул. Киевская, д. 12, кв. 5', /Киевская|кв\. 5/, '[адрес]'],
    ['Грузополучатель: ОсОО «Азия Транс», Бишкек', /Азия Транс/, '[сторона]'],
    ['Consignee: Asia Trans LLC, Bishkek', /Asia Trans/, '[сторона]'],
    ['Подпись: Иванов И.И.', /Иванов/, '[сторона]'],
    // без двоеточия метка стороны не работает (иначе страдают наименования товаров) — имя ловит правило ФИО
    ['Декларант Сыдыков А. Б. сообщил', /Сыдыков/, '[ФИО]'],
    ['Отгрузку принял Сыдыков А. Б., склад 3', /Сыдыков/, '[ФИО]'],
    ['Груз принял А.Б. Сыдыков в четверг', /Сыдыков/, '[ФИО]'],
    // голая цепочка из 14+ цифр: ИНН (14 в КР) и счёт (16), написанные без метки
    ['Плательщик 12345678901234 оплатил', /12345678901234/, '[идентификатор]'],
    ['Перевод на 1234567890123456 вчера', /1234567890123456/, '[идентификатор]'],
    ['Контактное лицо: Иванов Иван', /Иванов/, '[ФИО]'],
    ['WhatsApp +996700112233', /996700112233/, '[телефон]'],
  ];
  for (const [src, mustGo, mustStay] of gone) {
    const out = redactPersonal(src);
    assert.ok(!mustGo.test(out), `не вырезано: ${src} → ${out}`);
    assert.ok(out.includes(mustStay), `нет пометки ${mustStay}: ${src} → ${out}`);
  }
  console.log('PASS: почта, телефон, карта, ИНН, счёт, паспорт, адрес, стороны и ФИО заменяются пометками');

  // ── что обязано остаться: без этого нет ни классификации, ни расчёта ──
  const keep = 'Инвойс № INV-2026/0917 от 17.09.2026, условия FOB Shanghai. Товар: смартфоны Redmi Note 13, '
    + 'код ТН ВЭД 8517130000, страна происхождения Китай, 1 000 шт, вес нетто 180,5 кг, брутто 210 кг, '
    + 'стоимость 12 500,00 USD по курсу 87,45 сом, фрахт 800 USD, НДС 12%, VIN JN1TANT31U0012345.';
  const kept = redactPersonal(keep);
  assert.equal(kept, keep, `изменено нужное:\n${keep}\n${kept}`);
  for (const must of ['8517130000', '12 500,00 USD', '180,5 кг', 'Китай', 'FOB Shanghai', 'INV-2026/0917', 'JN1TANT31U0012345'])
    assert.ok(kept.includes(must), `потеряно: ${must}`);
  console.log('PASS: код, суммы, валюта, вес, страна, Инкотермс, номер инвойса и VIN не тронуты');

  // ── наименования товаров, в которых метка сидит внутри фразы: не трогать ничего ──
  // Тот же класс ошибок, что «Smartphone 8517130000» → «Smartphone [телефон]»: метка обязана быть
  // отдельным словом с обеих сторон, у идентификаторов значение начинается с цифр, у текстовых
  // меток — после двоеточия. Иначе из описания товара пропадал код ТН ВЭД.
  for (const line of [
    'Smartphone 8517130000 qty 200 pcs', 'Telephone sets 8517110000', 'Headphones 8518300000, 500 pcs',
    'Microphone 8518100000', 'Address labels self-adhesive 4821100000', 'Passport covers leather 4202320000',
    'Account books 4820100000', 'Buyer guide 4901990000', 'Seller relay 8536490000',
    'ИННОВАЦИЯ ОсОО, трубы 7304190000', 'ПИНцет медицинский 9018390000', 'Телефоны мобильные 8517130000',
    'Адресные наклейки 4821100000', 'Директорский стол 9403300000',
    // длинные номера, которые нужны для ответа: контейнер, пломба, артикул, VIN, курс и вес
    'Контейнер MSKU1234567, пломба 0123456', 'Артикул 12345678901 серия A', 'VIN JN1TANT31U0012345',
    'Код 8517130000, курс 87,45 сом, 1 000 шт, вес 180,5 кг',
  ]) assert.equal(redactPersonal(line), line, `испорчено наименование товара: ${line}`);
  console.log('PASS: наименования товаров с «phone», «address», «account», «passport», «ИНН» внутри слов не тронуты');

  // ── строка расшифровки: сторона вырезана, но код и сумма на той же строке остались ──
  const row = redactPersonal('| Грузополучатель: ОсОО «Азия Транс» | 7304190000 | 5 000,00 USD |');
  assert.ok(!row.includes('Азия Транс') && row.includes('[сторона]'), row);
  for (const must of ['7304190000', '5 000,00 USD']) assert.ok(row.includes(must), `потеряно в строке таблицы: ${must}`);
  assert.ok(!/\](?=\S)/.test(redactPersonal('Seller: Shenzhen Co, 8517130000 — 12 500,00 USD')), 'пометка слиплась со следующим словом');
  console.log('PASS: в строке таблицы вырезана только сторона — код, сумма и разделители целы');

  // ── целый документ: ни одна персональная строка не уходит, ни одна нужная не теряется ──
  // Замер на кусках настоящих бумаг (инвойс, банковский блок, CMR, упаковочный лист) — именно он
  // показал, что без меток «водитель», «перевозчик», «плательщик», «payer», «beneficiary»
  // в модель уходило полное ФИО водителя и стороны платежа, а SWIFT и БИК проходили мимо.
  const DOC = [
    'INVOICE No INV-2026/0917 dated 17.09.2026',
    'Seller: Shenzhen Tech Trading Co., Ltd.',
    'Beneficiary bank: Bank of China, Shenzhen branch',
    'Swift code: BKCHCNBJ45A',
    'Account No 7654321098765432',
    'Payer: ОсОО «Азия Импорт», ИНН 01234567890123',
    'Адрес: г. Бишкек, ул. Киевская, 12, оф. 5',
    'Тел/факс: +996 312 900 100',
    'E-mail: sales@shenzhen-tech.example',
    'Delivery terms: FOB Shanghai',
    '| 1 | Smartphone Redmi Note 13, 8 GB | 8517130000 | 200 pcs | 62,50 USD | 12 500,00 USD |',
    '| 2 | Headphones wireless | 8518300000 | 500 pcs | 3,00 USD | 1 500,00 USD |',
    'Total: 14 000,00 USD, net weight 180,5 kg, gross 210 kg',
    'Перевозчик: ИП Сыдыков А. Б.',
    'Водитель: Сыдыков Азамат Бакытович, паспорт AN2345678',
    'Госномер 01KG123ABC, прицеп 01KG456DEF',
    'Контракт № 12/26 от 01.09.2026',
    'Плательщик: ОсОО «Азия Импорт», р/с 1234567890123456 в ОАО «Банк», БИК 128009',
    'Упаковочный лист: 20 коробок, 8517130000, 180,5 кг нетто',
    'Подпись: Иванов И.И., менеджер по логистике',
  ].join('\n');
  const clean = redactPersonal(DOC);
  for (const secret of ['Shenzhen Tech Trading', 'BKCHCNBJ45A', '7654321098765432', '01234567890123', 'Киевская',
    '+996 312 900 100', 'sales@shenzhen-tech.example', 'Сыдыков', 'AN2345678', '01KG123ABC', '1234567890123456', '128009', 'Иванов'])
    assert.ok(!clean.includes(secret), `ушло в модель: ${secret}\n${clean}`);
  for (const must of ['8517130000', '8518300000', '12 500,00 USD', '14 000,00 USD', '180,5 kg', '180,5 кг',
    'FOB Shanghai', 'INV-2026/0917', 'Smartphone Redmi Note 13', 'Headphones wireless', '200 pcs', '20 коробок', 'Контракт № 12/26'])
    assert.ok(clean.includes(must), `потеряно нужное: ${must}\n${clean}`);
  assert.ok(!/\](?=[0-9A-Za-zА-Яа-яЁё])/.test(clean), 'пометка слиплась со следующим словом');
  console.log('PASS: целый документ — реквизиты, банк, водитель и номера вырезаны, товар, суммы и вес целы');

  // ── повторная очистка ничего не меняет: текст чистится в браузере (/clean) и ещё раз в ask() ──
  for (const line of [
    'Тел. +996700112233, ИНН 12345678901234', 'Seller: Shenzhen Co, 8517130000 — 12 500,00 USD',
    'Адрес: Бишкек, Киевская 12', 'Контактное лицо: Иванов Иван', 'ivan@example.kg и карта 4276 3800 1234 5678',
  ]) {
    const once = redactPersonal(line), twice = redactPersonal(once);
    assert.equal(twice, once, `повторная очистка изменила текст: ${line}`);
  }
  console.log('PASS: повторная очистка ничего не меняет');

  // ── ask(): до модели доходит уже очищенный текст вопроса и документа ──
  const sent = [];
  global.fetch = async (url, opts) => {
    sent.push(opts.body);
    return { ok: true, json: async () => ({ content: [{ type: 'text', text: 'Ответ по коду 8517130000.' }], usage: { input_tokens: 10, output_tokens: 5 } }) };
  };
  await ask([{ role: 'user', content: 'Мой телефон +996 700 111 222, посчитай 8517130000 на 12 500 USD' }],
    { docs: [{ name: 'invoice.pdf', text: 'Seller: Shenzhen Tech Co.\nИНН 12345678901234\nsales@shenzhen.example\n8517130000 — 12 500,00 USD' }] });
  const body = sent.join('\n');
  for (const secret of ['+996 700 111 222', '12345678901234', 'sales@shenzhen.example', 'Shenzhen Tech Co'])
    assert.ok(!body.includes(secret), `ушло в модель: ${secret}`);
  for (const must of ['8517130000', '12 500,00 USD', '[телефон]', '[идентификатор]', '[почта]', '[сторона]'])
    assert.ok(body.includes(must), `не дошло до модели: ${must}`);
  console.log('PASS: ask() отправляет очищенные вопрос и документ, код и сумма на месте');
})().catch((e) => { console.error(e); process.exitCode = 1; });
